#!/usr/bin/env python3
"""Build a small, offline English prompt bank. Requires espeak-ng and ffmpeg.

No Google audio or proprietary system voices are copied. Audio is generated from
these original phrases using eSpeak NG's built-in en-us voice (no MBROLA data).
"""
from pathlib import Path
import subprocess
import tempfile
import struct

ROOT = Path(__file__).resolve().parents[1]
PHRASES = [
    ("None", ""), ("Ahead", "Ahead,"), ("Mile", "In one mile,"),
    ("HalfMile", "In half a mile,"), ("QuarterMile", "In a quarter mile,"),
    ("Feet500", "In five hundred feet,"), ("Feet200", "In two hundred feet,"),
    ("Now", "Now,"), ("Straight", "Continue straight."), ("Left", "Turn left."),
    ("Right", "Turn right."), ("SlightLeft", "Keep left."), ("SlightRight", "Keep right."),
    ("UTurn", "Make a U turn."), ("Roundabout", "At the roundabout, follow the exit shown on screen."),
    ("Arrive", "You are arriving at your destination."), ("Rerouting", "Rerouting."),
    ("Test", "Navigation speaker ready. Turn left. Turn right."),
]

bank = bytearray()
rows = []
with tempfile.TemporaryDirectory(prefix="companion-voice-") as tmp:
    for name, phrase in PHRASES:
        pcm = b""
        if phrase:
            wav, raw = Path(tmp) / "voice.wav", Path(tmp) / "voice.pcm"
            subprocess.run(["espeak-ng", "-v", "en-us", "-s", "155", "-a", "90", "-w", str(wav), phrase], check=True)
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav), "-ar", "16000", "-ac", "1", "-f", "s16le", str(raw)], check=True)
            pcm = raw.read_bytes()
            assert len(pcm) % 2 == 0 and len(pcm) < 32000 * 8
            assert max(abs(x[0]) for x in struct.iter_unpack('<h', pcm)) > 100
        rows.append(f"    {{{len(bank)}, {len(pcm)}}}, // {name}: {phrase}".rstrip())
        bank.extend(pcm)
assert len(bank) < 1_400_000
(ROOT / "firmware/assets/navigation.pcm").write_bytes(bank)
(ROOT / "firmware/include/VoiceClipData.h").write_text(
    "// Generated by tools/generate_navigation_voice.py; PCM16 LE mono, 16 kHz.\n"
    "#pragma once\n#include <cstdint>\nstruct VoiceClipRange { uint32_t offset,size; };\n"
    "inline constexpr VoiceClipRange VoiceClips[]={\n" + '\n'.join(rows) + "\n};\n")
print(f"Generated {len(PHRASES)-1} prompts, {len(bank)} bytes, {len(bank)/32000:.1f} seconds.")
